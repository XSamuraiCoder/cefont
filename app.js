(() => {
  const $ = selector => document.querySelector(selector);
  const fileInput = $('#font-file');
  const dropzone = $('#dropzone');
  const selectedFile = $('#selected-file');
  const convertButton = $('#convert-button');
  const convertLabel = $('#convert-label');
  const progress = $('#progress');
  const progressBar = $('#progress-bar');
  const runtimeNote = $('#runtime-note');
  const runtimeMessage = $('#runtime-message');
  const previewStyle = document.createElement('style');
  document.head.appendChild(previewStyle);

  let currentFile = null;
  let previewUrl = null;
  let converted = null;
  let busy = false;
  const downloadUrls = [];

  function say(message, isError = false) {
    runtimeMessage.textContent = message;
    runtimeNote.classList.toggle('is-error', isError);
  }

  function setProgress(value) {
    progress.hidden = value == null;
    if (value != null) progressBar.style.width = `${value}%`;
  }

  function parseSizes() {
    const parts = $('#font-size').value.split(/[,\s]+/).filter(Boolean);
    const sizes = parts.map(value => /^\d+$/.test(value) ? Number(value) : NaN);
    const valid = sizes.length > 0 && sizes.length <= 8
      && sizes.every(size => Number.isInteger(size) && size >= 4 && size <= 64)
      && new Set(sizes).size === sizes.length;
    return { sizes, valid };
  }

  function settingsKey() {
    return [
      currentFile && `${currentFile.name}:${currentFile.size}:${currentFile.lastModified}`,
      $('#font-size').value,
      $('#font-weight').value,
      $('#output-name').value,
      $('#overhang-range').value,
      $('#tracking-range').value
    ].join('|');
  }

  function updateHelp() {
    const { sizes, valid } = parseSizes();
    const sizeHelp = $('#size-help');
    sizeHelp.classList.toggle('is-error', !valid);
    sizeHelp.textContent = valid
      ? sizes.length > 1
        ? `${sizes.length} sizes in one AppVar: index 0 = ${sizes[0]} px, 1 = ${sizes[1]} px${sizes.length > 2 ? ', …' : ''}.`
        : 'Pixel height, 4–64. Use commas to pack several (12,16).'
      : 'Enter 1–8 distinct whole-number sizes from 4 to 64.';

    const name = $('#output-name').value;
    $('#name-help').textContent = `${name.length}/8 · Name on the calculator. Letters/digits, max 8, start with a letter.`;
    for (const range of [$('#overhang-range'), $('#tracking-range')]) {
      range.style.setProperty(
        '--fill',
        `${(range.value - range.min) / (range.max - range.min) * 100}%`
      );
    }
    $('#overhang-value').textContent = `${$('#overhang-range').value} px`;
    const tracking = Number($('#tracking-range').value);
    $('#tracking-value').textContent = `${tracking > 0 ? '+' : tracking < 0 ? '−' : ''}${Math.abs(tracking)} px`;
  }

  function drawBitmapText(record, text, color) {
    const scale = 2;
    const glyphs = Array.from(text, character => record.glyphs[character.codePointAt(0)]);
    const width = glyphs.reduce((sum, glyph) => sum + (glyph ? glyph.width : 0), 0);
    const canvas = document.createElement('canvas');
    canvas.width = Math.max(1, width * scale);
    canvas.height = record.height * scale;
    canvas.className = 'specimen-canvas';
    const context = canvas.getContext('2d');
    context.fillStyle = color;
    let offset = 0;
    for (const glyph of glyphs) {
      if (!glyph) continue;
      glyph.rows.forEach((row, y) => {
        for (let x = 0; x < row.length; x++) {
          if (row[x] === '#') context.fillRect((offset + x) * scale, y * scale, scale, scale);
        }
      });
      offset += glyph.width;
    }
    return canvas;
  }

  function renderPreview() {
    const rows = $('#specimen-rows');
    const empty = $('#specimen-empty');
    const badge = $('#specimen-badge');
    const note = $('#specimen-note');
    const { sizes, valid } = parseSizes();
    const exact = converted && converted.key === settingsKey()
      ? converted.fontRecords
      : null;
    if (!currentFile || !valid) {
      rows.textContent = '';
      empty.hidden = false;
      empty.lastElementChild.textContent = currentFile
        ? 'Enter valid sizes to preview.'
        : 'Choose a font to see it at every size.';
      badge.hidden = true;
      note.hidden = true;
      return;
    }

    const text = $('#preview-text').value || 'The quick brown fox jumps over the lazy dog';
    const color = getComputedStyle(document.documentElement).getPropertyValue('--ink').trim() || '#000';
    rows.textContent = '';
    empty.hidden = true;
    badge.hidden = false;
    badge.textContent = exact ? 'Hinted FreeType · 1-bit' : 'Browser preview';
    badge.classList.toggle('is-exact', !!exact);
    note.hidden = false;
    note.textContent = exact
      ? 'Exact monochrome glyphs generated by hinted FreeType and included in the AppVar.'
      : 'Approximate preview. Convert to see the hinted FreeType 1-bit glyphs.';

    sizes.forEach((size, index) => {
      const row = document.createElement('div');
      row.className = 'specimen-row';
      const label = document.createElement('div');
      label.className = 'specimen-label';
      label.textContent = `${size} px`;
      const body = document.createElement('div');
      body.className = 'specimen-text';
      if (exact && exact[index]) {
        const height = document.createElement('small');
        height.textContent = `index ${index} · ${exact[index].height} px tall`;
        label.appendChild(height);
        body.appendChild(drawBitmapText(exact[index], text, color));
      } else {
        body.textContent = text;
        body.style.fontSize = `${size}px`;
        body.style.fontFamily = '"UploadedFontPreview", sans-serif';
        body.style.fontWeight = $('#font-weight').value === 'bold' ? '700' : '400';
        const indexLabel = document.createElement('small');
        indexLabel.textContent = `index ${index}`;
        label.appendChild(indexLabel);
      }
      row.append(label, body);
      rows.appendChild(row);
    });
  }

  function showMatches(matches) {
    const result = $('#compare-results');
    const rows = $('#compare-rows');
    rows.textContent = '';
    for (const match of matches) {
      const row = document.createElement('tr');
      const size = document.createElement('th');
      size.scope = 'row';
      size.textContent = `${match.size}px`;
      row.append(size);
      for (const value of [
        `${match.score.toFixed(2)}%`,
        `${match.ink.toFixed(2)}%`,
        `${match.width_match.toFixed(2)}%`,
        `${match.compared}/${match.requested}`
      ]) {
        const cell = document.createElement('td');
        cell.textContent = value;
        row.appendChild(cell);
      }
      rows.appendChild(row);
    }
    $('#compare-summary').textContent = 'Printable ASCII range';
    result.hidden = false;
  }

  function clearMatches() {
    $('#compare-results').hidden = true;
    $('#compare-rows').textContent = '';
    $('#compare-summary').textContent = '';
  }

  function setFile(file) {
    if (!file) return;
    if (!/\.(ttf|otf)$/i.test(file.name)) {
      say('Choose a .ttf or .otf font file.', true);
      return;
    }
    if (!file.size || file.size > 20 * 1024 * 1024) {
      say('Font file must be between 1 byte and 20 MB.', true);
      return;
    }
    currentFile = file;
    converted = null;
    $('#file-name').textContent = file.name;
    $('#file-details').textContent = `${formatSize(file.size)} · Ready to configure`;
    selectedFile.hidden = false;
    dropzone.hidden = true;
    const baseName = normalizeName(file.name.replace(/\.[^.]+$/, ''));
    if (baseName && !$('#output-name').dataset.touched) $('#output-name').value = baseName;
    if (previewUrl) URL.revokeObjectURL(previewUrl);
    previewUrl = URL.createObjectURL(file);
    previewStyle.textContent = `@font-face{font-family:"UploadedFontPreview";src:url("${previewUrl}");font-display:swap}`;
    convertButton.disabled = false;
    $('#convert-label').textContent = 'Convert font';
    clearMatches();
    updateHelp();
    renderPreview();
    say('Ready. Conversion runs locally in your browser.');
  }

  function clearFile() {
    currentFile = null;
    converted = null;
    selectedFile.hidden = true;
    dropzone.hidden = false;
    fileInput.value = '';
    if (previewUrl) URL.revokeObjectURL(previewUrl);
    previewUrl = null;
    previewStyle.textContent = '';
    convertButton.disabled = true;
    $('#convert-label').textContent = 'Choose a font to continue';
    clearMatches();
    renderPreview();
    say('Choose a font to convert. Font data stays in your browser.');
  }

  function formatSize(bytes) {
    return bytes < 1024 ? `${bytes} B` : `${(bytes / 1024).toFixed(1)} KB`;
  }

  function normalizeName(value) {
    let name = value.replace(/[^a-z0-9]/gi, '').toUpperCase().slice(0, 8);
    if (name && !/^[A-Z]/.test(name)) name = `F${name}`.slice(0, 8);
    return name;
  }

  async function convert() {
    if (!currentFile || busy) return;
    const { sizes, valid } = parseSizes();
    if (!valid) {
      say('Enter 1–8 distinct whole-number sizes from 4 to 64.', true);
      return;
    }
    busy = true;
    convertButton.disabled = true;
    convertButton.classList.add('is-busy');
    $('#convert-label').textContent = 'Converting with FreeType WASM…';
    $('#compare-results').hidden = true;
    setProgress(15);
    try {
      const name = $('#output-name').value.trim() || 'MYFONT';
      if (!/^[A-Z][A-Z0-9]{0,7}$/.test(name)) {
        throw new Error('AppVar name must start with a letter and contain up to 8 letters or digits.');
      }
      const result = await window.CEfontRenderer.convert(
        await currentFile.arrayBuffer(),
        {
          name,
          sizes,
          weight: $('#font-weight').value,
          overhang: Number($('#overhang-range').value),
          tracking: Number($('#tracking-range').value)
        },
        setProgress
      );
      converted = { fontRecords: result.fontRecords, key: settingsKey() };
      showMatches(result.info.matches);
      addResult(result.filename, result.bytes, result.info);
      renderPreview();
      setProgress(100);
      say('Done. Converted locally with hinted FreeType WebAssembly.');
    } catch (error) {
      console.error(error);
      say(`Conversion failed: ${error.message || error}`, true);
      setProgress(null);
    } finally {
      busy = false;
      convertButton.disabled = !currentFile;
      convertButton.classList.remove('is-busy');
      $('#convert-label').textContent = currentFile ? 'Convert font' : 'Choose a font to continue';
      window.setTimeout(() => setProgress(null), 900);
    }
  }

  function addResult(filename, bytes, info) {
    downloadUrls.splice(0).forEach(URL.revokeObjectURL);
    const list = $('#results-list');
    list.textContent = '';
    const url = URL.createObjectURL(new Blob([bytes], { type: 'application/octet-stream' }));
    downloadUrls.push(url);
    const item = document.createElement('div');
    item.className = 'result-item';
    item.innerHTML = '<div class="result-icon"><span class="ms">description</span></div><div class="result-info"><strong></strong><span></span></div><a class="download-button"><span class="ms">download</span>Download</a>';
    item.querySelector('strong').textContent = filename;
    item.querySelector('.result-info span').textContent =
      `${formatSize(bytes.length)} · AppVar ${info.appvar} · ${info.fonts} size${info.fonts === 1 ? '' : 's'} (${info.sizes.join(', ')} px)`;
    const hint = document.createElement('span');
    hint.className = 'result-preview';
    hint.textContent = `fontlib_GetFontByIndex("${info.appvar}", 0)`;
    item.querySelector('.result-info').appendChild(hint);
    const link = item.querySelector('a');
    link.href = url;
    link.download = filename;
    list.appendChild(item);
    list.hidden = false;
    $('#results-empty').hidden = true;
    $('#results-count').textContent = '1 file';
  }

  const themeToggle = $('#theme-toggle');
  themeToggle.addEventListener('click', () => {
    const theme = document.documentElement.getAttribute('data-theme') === 'dark' ? 'light' : 'dark';
    document.documentElement.setAttribute('data-theme', theme);
    themeToggle.firstElementChild.textContent = theme === 'dark' ? 'light_mode' : 'dark_mode';
    const meta = $('meta[name="theme-color"]');
    if (meta) meta.content = theme === 'dark' ? '#0e111d' : '#f5f6fb';
    try { localStorage.setItem('cefont-theme', theme); } catch (error) {
      console.info('Could not save theme preference.', error);
    }
    renderPreview();
  });
  $('#remove-file').addEventListener('click', clearFile);
  fileInput.addEventListener('change', () => setFile(fileInput.files[0]));
  dropzone.addEventListener('click', () => fileInput.click());
  dropzone.addEventListener('keydown', event => {
    if (event.key === 'Enter' || event.key === ' ') {
      event.preventDefault();
      fileInput.click();
    }
  });
  for (const eventName of ['dragenter', 'dragover']) {
    dropzone.addEventListener(eventName, event => {
      event.preventDefault();
      dropzone.classList.add('is-dragging');
    });
  }
  for (const eventName of ['dragleave', 'drop']) {
    dropzone.addEventListener(eventName, event => {
      event.preventDefault();
      dropzone.classList.remove('is-dragging');
    });
  }
  dropzone.addEventListener('drop', event => setFile(event.dataTransfer.files[0]));
  $('#convert-button').addEventListener('click', convert);
  for (const selector of ['#font-size', '#font-weight', '#output-name', '#preview-text', '#overhang-range', '#tracking-range']) {
    $(selector).addEventListener('input', () => {
      updateHelp();
      if (converted && converted.key !== settingsKey()) {
        converted = null;
        clearMatches();
      }
      renderPreview();
    });
  }
  $('#font-weight').addEventListener('change', renderPreview);
  $('#output-name').addEventListener('input', event => {
    const input = event.currentTarget;
    input.value = normalizeName(input.value);
    input.dataset.touched = 'true';
  });
  updateHelp();
  renderPreview();
  $('#runtime-status').lastChild.textContent = ' Static · FreeType WebAssembly · local';
  convertButton.disabled = !currentFile;
  say('Ready. Fonts are converted in your browser and never uploaded.');
})();
